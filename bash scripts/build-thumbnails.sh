#!/bin/sh
# Pack every games/<slug>/thumbnail.png into one sprite sheet (assets/thumbnails.webp), so the shelf loads one image
# instead of one per game, and write css/thumbnails.css, which points each cartridge at its tile by slug.
# Run it again whenever a game is added or removed. Needs ImageMagick (with WebP support).
set -e
cd "$(dirname "$(realpath "$0")")/.."
thumbnails=$(ls games/*/thumbnail.png)
n=$(echo "$thumbnails" | wc -l)
cols=$(awk "BEGIN { c = int(sqrt($n)); if (c * c < $n) c++; print c }")
rows=$(( (n + cols - 1) / cols ))

# 128px tiles with 1px of black around each (so 2px between tiles), so nothing bleeds in from the next thumbnail when
# the page is zoomed. saved as lossless WebP (about 10% smaller than an oxipng'd indexed PNG, and pixel-identical)
magick montage $thumbnails -tile "${cols}x$rows" -geometry 128x128+1+1 -background black -strip \
  -define webp:lossless=true -define webp:method=6 -quality 100 assets/thumbnails.webp
v=$(md5sum assets/thumbnails.webp | cut -c1-8)  # cache-buster, so a rebuilt sheet isn't served stale

# offsets are in sheet pixels: tile (c, r) starts at 130c + 1, 130r + 1 (128px of art plus the 2px gap per step).
# the thumbnail box is smaller than 128px, so the sheet and offsets are scaled by its width over 128 (--s)
{
  echo "/* generated by build-thumbnails.sh: each cartridge's thumbnail art, as a tile of thumbnails.webp */"
  echo ".cart { container-type: inline-size; }  /* so the thumbnail can measure the cartridge (cqw) */"
  echo ".cart .thumbnail {"
  echo "  --s: calc((100cqw - 6px) / 128);  /* the thumbnail's width (the cartridge's content minus the thumbnail's border) per art pixel */"
  echo "  background: #000 url(\"../assets/thumbnails.webp?v=$v\") no-repeat;"
  echo "  background-size: calc($(magick identify -format %w assets/thumbnails.webp) * var(--s)) auto;"
  echo "  background-position: calc(var(--x) * var(--s) * -1) calc(var(--y) * var(--s) * -1);"
  echo "}"
  i=0
  for thumbnail in $thumbnails; do
    slug=$(basename "$(dirname "$thumbnail")")
    echo ".cart[fx-action=\"games/$slug/meta.html\"] .thumbnail { --x: $((i % cols * 130 + 1)); --y: $((i / cols * 130 + 1)); }"
    i=$((i + 1))
  done
} > css/thumbnails.css
echo "packed $n thumbnails into assets/thumbnails.webp (${cols}x$rows, $(wc -c < assets/thumbnails.webp) bytes)"
